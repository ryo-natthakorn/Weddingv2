import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const server = await createServer({ server:{host:'127.0.0.1',port:0}, logLevel:'silent' });
await server.listen();
const browser=await chromium.launch({ args:['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
try {
  for(const [width,height] of [[390,844],[1280,896]]){
    const page=await browser.newPage({viewport:{width,height}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.route(/^https:\/\//,r=>r.abort());
    await page.goto(server.resolvedUrls.local[0]+'?gallery=webgl');
    await page.getByRole('slider').press('Enter');
    const gallery=page.locator('.pw-orbit');
    await gallery.scrollIntoViewIfNeeded();
    await page.waitForFunction(()=>document.querySelector('[data-gallery-ready="true"]'));
    assert.equal(await gallery.getAttribute('data-renderer'),'webgl','WebGL renderer chosen');
    const canvas=gallery.locator('canvas');
    assert.equal(await canvas.count(),1);
    await page.mouse.move(0,0);await page.waitForTimeout(1500);
    const shot=()=>canvas.screenshot().then(b=>b.toString('base64'));
    const a=await shot();await page.waitForTimeout(700);
    assert.notEqual(await shot(),a,'ring drifts');
    const counter=page.locator('[data-gallery-counter]'), dialogs=()=>page.getByRole('dialog').count();
    const label=await counter.textContent();
    await page.getByRole('button',{name:/^(Next photo|รูปถัดไป)$/}).click();
    await page.waitForTimeout(750);
    assert.notEqual(await counter.textContent(),label,'next arrow turns ring');
    const box=await canvas.boundingBox();
    const beforeDrag=await shot();
    await page.mouse.move(box.x+box.width*.3,box.y+box.height*.55);await page.mouse.down();
    await page.mouse.move(box.x+box.width*.3+120,box.y+box.height*.55,{steps:6});await page.mouse.up();
    assert.notEqual(await shot(),beforeDrag,'drag spins ring');
    assert.equal(await dialogs(),0,'drag does not open viewer');
    await page.mouse.move(0,0);await page.waitForTimeout(2000);
    const front=gallery.locator('.pw-orbit-sr[tabindex="0"]');
    assert.equal(await gallery.locator('.pw-orbit-sr[tabindex="0"]').count(),1,'one tabbable print');
    await front.focus();await page.waitForTimeout(100);
    await front.press('Enter');await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({state:'detached'});
    assert.equal(await front.evaluate(el=>el===document.activeElement),true,'focus returns to print');
    await page.mouse.move(0,0);await page.waitForTimeout(800);
    const center=await canvas.boundingBox();
    await page.mouse.click(center.x+center.width/2,center.y+center.height*.62);
    await page.waitForTimeout(300);
    assert.equal(await dialogs(),1,'tapping the front print opens it');
    await page.keyboard.press('Escape');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal overflow');
    await gallery.screenshot({path:join(tmpdir(),`gallery-webgl-${width}.png`)});
    assert.deepEqual(errors,[]);
    console.log(`PASS ${width}x${height}: webgl drift, arrows, drag, keyboard viewer, tap front`);
    await page.close();
  }
} finally {await browser.close();await server.close();}
